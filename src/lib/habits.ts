export const WEEKDAYS = ['пн', 'вт', 'ср', 'чт', 'пт', 'сб', 'вс'];
export const weekdayIndex = (d: Date) => (d.getDay() + 6) % 7;

export type Freq = 'days' | 'every' | 'weekly';
export const freqOf = (h: Pick<Habit, 'freq'>): Freq => h.freq ?? 'days';
export const everyOf = (h: Pick<Habit, 'everyDays'>) => Math.max(2, h.everyDays ?? 2);
export const timesOf = (h: Pick<Habit, 'timesPerWeek'>) => Math.min(6, Math.max(1, h.timesPerWeek ?? 1));

// Для режима «по дням недели»: запланирована ли привычка на этот день.
// В гибких режимах конкретных дней нет — любой день подходит.
export const scheduledOn = (h: Habit, d: Date) =>
  freqOf(h) !== 'days' || !h.days || h.days.length === 0 || h.days.includes(weekdayIndex(d));

export const scheduleLabel = (h: Pick<Habit, 'freq' | 'days' | 'everyDays' | 'timesPerWeek'>) => {
  const f = freqOf(h);
  if (f === 'every') {
    const n = everyOf(h);
    return n === 2 ? 'через день' : `раз в ${n} ${n < 5 ? 'дня' : 'дней'}`;
  }
  if (f === 'weekly') {
    const n = timesOf(h);
    return n === 1 ? 'раз в неделю' : `${n} раза в неделю`;
  }
  if (!h.days || h.days.length === 0 || h.days.length === 7) return 'каждый день';
  const s = [...h.days].sort().join(',');
  if (s === '0,1,2,3,4') return 'по будням';
  if (s === '5,6') return 'по выходным';
  return [...h.days].sort().map((i) => WEEKDAYS[i]).join(', ');
};

const startOfDay = (d: Date) => new Date(d.getFullYear(), d.getMonth(), d.getDate());
const daysBetween = (a: string, b: Date) => Math.round((startOfDay(b).getTime() - parseDay(a).getTime()) / 86400000);
const weekStart = (d: Date) => addDays(startOfDay(d), -weekdayIndex(d));

// Сколько раз в день нужно сделать привычку (например, стакан воды 4 раза)
export const perDayOf = (h: Pick<Habit, 'perDay'>) => Math.max(1, Math.min(20, h.perDay ?? 1));

type HabitRef = Pick<Habit, 'id' | 'perDay'>;

// Сколько раз привычка отмечена в этот день
export const countOn = (logs: HabitLog[], habitId: string, day: string) =>
  logs.filter((l) => !l.deleted && l.habitId === habitId && l.day === day).length;

// Дни, когда дневная норма выполнена полностью (для серий, расписаний и календаря)
const doneDays = (logs: HabitLog[], h: HabitRef) => {
  const need = perDayOf(h);
  const counts = new Map<string, number>();
  for (const l of logs) if (!l.deleted && l.habitId === h.id) counts.set(l.day, (counts.get(l.day) ?? 0) + 1);
  return [...counts.entries()].filter(([, n]) => n >= need).map(([k]) => k).sort();
};

// Сколько раз сделано на неделе, в которую входит день d
const doneInWeek = (days: string[], d: Date) => {
  const from = dayKey(weekStart(d));
  const to = dayKey(addDays(weekStart(d), 6));
  return days.filter((k) => k >= from && k <= to).length;
};

// Нужно ли делать закреплённую привычку в этот день (сделанная сегодня тоже показывается — уже отмеченной)
export function isDueOn(h: Habit, logs: HabitLog[], d = appNow()): boolean {
  const today = dayKey(d);
  const days = doneDays(logs, h);
  if (days.includes(today)) return true;
  const f = freqOf(h);
  if (f === 'days') return scheduledOn(h, d);
  if (f === 'every') {
    const last = days.filter((k) => k < today).pop();
    return !last || daysBetween(last, d) >= everyOf(h);
  }
  return doneInWeek(days, d) < timesOf(h);
}

// Для календаря «Неделя»: стоит ли привычка в этот день и сделана ли.
// Прошедшие дни — по факту (что было сделано, и что пропущено по расписанию).
// Будущие: по дням недели — по расписанию; «раз в N дней» — прогноз от последнего выполнения;
// «N раз в неделю» конкретных дней нет — такие показываются отдельной строкой над неделей.
export function calendarPlan(h: Habit, logs: HabitLog[], d: Date, now = appNow()): { show: boolean; done: boolean; missed: boolean } {
  const key = dayKey(d);
  const today = dayKey(now);
  const days = doneDays(logs, h);
  const done = days.includes(key);
  if (done) return { show: true, done, missed: false };
  const f = freqOf(h);
  if (f === 'weekly') return { show: false, done, missed: false };
  if (f === 'days') return { show: scheduledOn(h, d), done, missed: key < today && scheduledOn(h, d) };
  // раз в N дней
  if (key < today) return { show: false, done, missed: false };
  const n = everyOf(h);
  const last = days.filter((k) => k <= today).pop();
  let next = startOfDay(now);
  if (last) {
    const fromLast = addDays(parseDay(last), n);
    if (fromLast > next) next = fromLast;
  }
  const diff = Math.round((startOfDay(d).getTime() - next.getTime()) / 86400000);
  return { show: diff >= 0 && diff % n === 0, done, missed: false };
}

export const weeklyProgress = (h: Habit, logs: HabitLog[], weekDay: Date) => ({
  done: Math.min(doneInWeek(doneDays(logs, h), weekDay), timesOf(h)),
  need: timesOf(h),
});

// Напоминание на главном экране: закреплённая привычка не выполнена в своём периоде.
// Каждый день / по дням недели — сегодня не сделана (или норма не набрана);
// раз в N дней — подошёл или прошёл срок; N раз в неделю — недельная норма не набрана.
// Возвращает короткую подпись или null, если напоминать не о чем.
export function reminderFor(h: Habit, logs: HabitLog[], d = appNow()): { label: string; late: boolean } | null {
  if (h.deleted || !h.mine) return null;
  const today = dayKey(d);
  const count = countOn(logs, h.id, today);
  const need = perDayOf(h);
  const f = freqOf(h);
  if (f === 'weekly') {
    const days = doneDays(logs, h);
    const done = doneInWeek(days, d);
    const times = timesOf(h);
    if (done >= times) return null;
    const left = 7 - weekdayIndex(d); // сколько дней недели осталось, включая сегодня
    return { label: `${done}/${times} на неделе · осталось ${left} ${left === 1 ? 'день' : left < 5 ? 'дня' : 'дней'}`, late: times - done >= left };
  }
  if (!isDueOn(h, logs, d) || count >= need) return null;
  if (f === 'every') {
    const last = doneDays(logs, h).filter((k) => k < today).pop();
    const since = last ? daysBetween(last, d) : null;
    const over = since === null ? 0 : since - everyOf(h);
    return { label: over > 0 ? `просрочено на ${over} дн.` : 'пора сегодня', late: over > 0 };
  }
  return { label: need > 1 ? `${count}/${need} сегодня` : 'сегодня', late: false };
}

// Подсказка о периоде: «на этой неделе 1 из 2», «следующий раз через 2 дня»
export function periodInfo(h: Habit, logs: HabitLog[], d = appNow()): string | null {
  const f = freqOf(h);
  const days = doneDays(logs, h);
  if (f === 'weekly') return `на этой неделе ${Math.min(doneInWeek(days, d), timesOf(h))} из ${timesOf(h)}`;
  if (f === 'every') {
    const last = days.filter((k) => k <= dayKey(d)).pop();
    if (!last) return 'можно сегодня';
    const left = everyOf(h) - daysBetween(last, d);
    if (left <= 0) return 'пора сегодня';
    return left === 1 ? 'следующий раз завтра' : `следующий раз через ${left} ${left < 5 ? 'дня' : 'дней'}`;
  }
  return null;
}

