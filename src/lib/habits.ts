// Встроенные записи, которые убраны из пула (помечаем удалёнными, если пользователь их не менял)
const REMOVED_BUILTINS = ['h-dishes'];

// Обновить встроенный пул в уже сохранённых данных: добавить новые дела, обновить нетронутые, убрать снятые
export function upgradeBuiltinHabits(data: AppData): AppData {
  const habits = [...(data.habits ?? [])];
  for (const d of DEFAULT_HABITS) {
    const i = habits.findIndex((x) => x.id === d.id);
    if (i < 0) habits.push({ ...d });
    else if (habits[i].builtIn && habits[i].updatedAt < d.updatedAt) habits[i] = { ...d, mine: habits[i].mine, days: habits[i].days };
  }
  for (const id of REMOVED_BUILTINS) {
    const i = habits.findIndex((x) => x.id === id);
    if (i >= 0 && !habits[i].deleted && habits[i].updatedAt < BUILTIN_VERSION) habits[i] = { ...habits[i], deleted: true, updatedAt: BUILTIN_VERSION };
  }
  return { ...data, habits, habitLogs: data.habitLogs ?? [] };
}

