const PERSONALIZED_BUILTINS = ['h-dishwasher', 'h-paint', 'h-assemble'];

// Обновить встроенный пул в уже сохранённых данных: добавить новые дела, обновить нетронутые, убрать снятые
export function upgradeBuiltinHabits(data: AppData): AppData {
  const fresh = !data.habits || data.habits.length === 0;
  const habits = [...(data.habits ?? [])];
  for (const d of DEFAULT_HABITS) {
    const i = habits.findIndex((x) => x.id === d.id);
    // новые встроенные дела у существующего пользователя не закрепляются сами — решает он
    if (i < 0) habits.push({ ...d, mine: fresh ? d.mine : false });
    else if (habits[i].builtIn && habits[i].updatedAt < d.updatedAt) {
      const x = habits[i];
      habits[i] = { ...d, mine: x.mine, freq: x.freq, days: x.days, everyDays: x.everyDays, timesPerWeek: x.timesPerWeek, hidden: x.hidden };
    }
  }
  for (const id of REMOVED_BUILTINS) {
    const i = habits.findIndex((x) => x.id === id);
    if (i >= 0 && !habits[i].deleted && habits[i].updatedAt < BUILTIN_VERSION) habits[i] = { ...habits[i], deleted: true, updatedAt: BUILTIN_VERSION };
  }
  for (const id of PERSONALIZED_BUILTINS) {
    const i = habits.findIndex((x) => x.id === id);
    if (i >= 0 && habits[i].builtIn) habits[i] = { ...habits[i], builtIn: false, updatedAt: Math.max(habits[i].updatedAt, BUILTIN_VERSION) };
  }
  return { ...data, habits, habitLogs: data.habitLogs ?? [] };
}

